#!/bin/bash
# LibraCloud EC2 bootstrap (Amazon Linux 2023).
# Run automatically by the CloudFormation UserData on first boot. Safe to re-run:
#   sudo /usr/local/bin/libracloud-setup
#
# 1. installs Docker, Docker Compose, cron and the CloudWatch agent
# 2. downloads the production compose file and the deploy script from GitHub
# 3. reads secrets from AWS Secrets Manager and writes /opt/libracloud/.env (mode 600)
# 4. configures the CloudWatch agent (memory/disk metrics + deploy logs)
# 5. starts all containers and schedules the auto-deploy agent (every 2 minutes)
set -euo pipefail

source /etc/libracloud/stack.env
APP=/opt/libracloud
log() { echo "[$(date -Is)] $*" >&2; }   # stderr: keeps captured command output clean
retry() {   # retry <attempts> <command...>
  local n=$1; shift
  for ((i = 1; i <= n; i++)); do "$@" && return 0; log "retry $i/$n failed: $*"; sleep 10; done
  return 1
}
imds() {
  local t
  t=$(curl -s -X PUT http://169.254.169.254/latest/api/token -H "X-aws-ec2-metadata-token-ttl-seconds: 60")
  curl -s -H "X-aws-ec2-metadata-token: $t" "http://169.254.169.254/latest/meta-data/$1"
}

# CloudFormation attaches the Elastic IP shortly after boot, which briefly drops
# internet connections. Wait until the public IP has been stable for 15 seconds.
log "== 0. waiting for the public IP (Elastic IP) to settle"
prev=""; stable=0
for _ in $(seq 1 36); do
  ip=$(imds public-ipv4 || true)
  if [ -n "$ip" ] && [ "$ip" = "$prev" ]; then stable=$((stable + 1)); else stable=0; fi
  [ "$stable" -ge 3 ] && break
  prev=$ip; sleep 5
done
log "public IP: ${ip:-unknown}"

log "== 1. packages"
retry 5 dnf install -y -q docker jq cronie amazon-cloudwatch-agent
systemctl enable --now docker crond
if ! docker compose version >/dev/null 2>&1; then
  mkdir -p /usr/local/lib/docker/cli-plugins
  retry 5 curl -fsSL "https://github.com/docker/compose/releases/download/v2.32.4/docker-compose-linux-$(uname -m)" \
    -o /usr/local/lib/docker/cli-plugins/docker-compose
  chmod +x /usr/local/lib/docker/cli-plugins/docker-compose
fi
docker compose version

log "== 2. application files"
mkdir -p "$APP"
cd "$APP"
retry 5 curl -fsSL "$REPO_RAW/docker-compose.prod.yml" -o docker-compose.yml
retry 5 curl -fsSL "$REPO_RAW/scripts/auto-deploy.sh" -o /usr/local/bin/libracloud-deploy
chmod +x /usr/local/bin/libracloud-deploy
# Amazon RDS certificate bundle - lets the services verify the database's TLS certificate.
retry 5 curl -fsSL https://truststore.pki.rds.amazonaws.com/global/global-bundle.pem -o rds-ca.pem
chmod 644 rds-ca.pem

log "== 3. secrets from AWS Secrets Manager"
secret() { retry 3 aws secretsmanager get-secret-value --region "$AWS_REGION" --secret-id "$1" --query SecretString --output text; }
DB_JSON=$(secret "$DB_SECRET_ARN")
APP_JSON=$(secret "$APP_SECRET_ARN")
KEY_JSON=$(secret "$INTERNAL_SECRET_ARN")

umask 077
cat > .env <<EOF
# Generated by libracloud-setup on $(date -Is). Do not commit. Re-run libracloud-setup to refresh.
AWS_REGION=$AWS_REGION
IMAGE_PREFIX=$IMAGE_PREFIX
LOG_GROUP=$LOG_GROUP
ORIGIN_VERIFY=$ORIGIN_VERIFY
NODE_ENV=production
TRUST_PROXY=1
EMF_ENABLED=true
PGHOST=$DB_HOST
PGPORT=5432
PGDATABASE=libracloud
PGUSER=$(echo "$DB_JSON" | jq -r .username)
PGPASSWORD=$(echo "$DB_JSON" | jq -r .password)
DB_SSL=true
DB_SSL_CA=/etc/ssl/rds-ca.pem
JWT_SECRET=$(echo "$APP_JSON" | jq -r .JWT_SECRET)
ADMIN_EMAIL=$(echo "$APP_JSON" | jq -r .ADMIN_EMAIL)
ADMIN_PASSWORD=$(echo "$APP_JSON" | jq -r .ADMIN_PASSWORD)
INTERNAL_API_KEY=$(echo "$KEY_JSON" | jq -r .INTERNAL_API_KEY)
S3_BUCKET=$S3_BUCKET
SNS_TOPIC_ARN=$SNS_TOPIC_ARN
EOF
umask 022
echo "REPO_RAW=$REPO_RAW" > /etc/libracloud/deploy.env

log "== 4. CloudWatch agent"
cat > /opt/aws/amazon-cloudwatch-agent/etc/libracloud.json <<EOF
{
  "agent": { "metrics_collection_interval": 60, "omit_hostname": true },
  "metrics": {
    "append_dimensions": { "InstanceId": "\${aws:InstanceId}" },
    "metrics_collected": {
      "mem": { "measurement": ["mem_used_percent"] },
      "disk": { "measurement": ["used_percent"], "resources": ["/"], "drop_device": true }
    }
  },
  "logs": {
    "logs_collected": {
      "files": {
        "collect_list": [
          { "file_path": "/var/log/libracloud-deploy.log", "log_group_name": "$DEPLOY_LOG_GROUP", "log_stream_name": "{instance_id}/deploy" },
          { "file_path": "/var/log/libracloud-setup.log", "log_group_name": "$DEPLOY_LOG_GROUP", "log_stream_name": "{instance_id}/setup" }
        ]
      }
    }
  }
}
EOF
/opt/aws/amazon-cloudwatch-agent/bin/amazon-cloudwatch-agent-ctl -a fetch-config -m ec2 -s \
  -c file:/opt/aws/amazon-cloudwatch-agent/etc/libracloud.json

log "== 5. start LibraCloud"
touch /var/log/libracloud-deploy.log
for i in 1 2 3 4 5; do
  docker compose pull -q && break
  log "image pull failed (attempt $i) - are the GHCR packages public and has the pipeline run?"; sleep 30
done
docker compose up -d --remove-orphans
docker compose ps

log "== 6. auto-deploy agent (checks for new images every 2 minutes)"
echo "*/2 * * * * root /usr/local/bin/libracloud-deploy >> /var/log/libracloud-deploy.log 2>&1" > /etc/cron.d/libracloud-deploy
chmod 644 /etc/cron.d/libracloud-deploy

log "== done. Website: open the WebsiteURL output of the CloudFormation stack."
